// /character-sheet — turn one head-and-shoulders portrait into a 3840×2160 character
// sheet for reference-to-video models (MiniMax H3 R2V). See ADR/character-sheet.md.
//
// The table holds the input image, then one row per panel: an editable prompt on the
// left and that panel's result on the right, with a ↺ to re-run just that panel.
// Generate sends every panel to /api/character-sheet, attaching each existing result as
// `cached`, so the server only runs what is missing and re-composites the sheet. All of
// it is driven by state.characterSheet; every change dispatches
// 'character-sheet-changed', which chat.js turns into a session save and every open
// table turns into a redraw.

import {
  escapeHtml, isVideoUrl, COMFY_URL_DND_TYPE, progressPercent, progressCaption,
  CHARACTER_SHEET_PANELS, defaultCharacterSheetPrompts, normalizeCharacterSheet,
  characterSheetPanelsPayload,
} from './utils.js';
import { state } from './state.js';
import { addMessage, scrollBottom, deleteImageFile } from './dom.js';
import { openLightbox } from './lightbox.js';
import { buildComparisonSlider } from './editors.js';

// The one job a tab can have running: { jobId, keys:Set (still to come), current,
// status, tick, error }. Module-level, not per table, so a second table opened while
// a job runs shows the same progress and can't start a second job.
let activeJob = null;
let lastError = null;

// 👤 face-detail per panel key: { phase: 'dialog'|'running'|'compare', oldUrl, newUrl?, slider? }. Also
// module-level, so a redraw (or a second open table) keeps a pending comparison rather
// than wiping it. While any entry exists the sheet is "busy": no Generate, ↺ or source
// change, since either would swap out the panel the comparison is about.
const faceJobs = {};

function busy() {
  return !!activeJob || Object.keys(faceJobs).length > 0;
}

export function notifyCharacterSheetChanged() {
  document.dispatchEvent(new CustomEvent('character-sheet-changed'));
}

function sheet() {
  if (!state.characterSheet) state.characterSheet = normalizeCharacterSheet(null);
  return state.characterSheet;
}

function i2iWorkflow() {
  // eslint-disable-next-line no-undef
  return state.currentImage2ImageWorkflow || (typeof DEFAULT_IMAGE2IMAGE_WORKFLOW !== 'undefined' ? DEFAULT_IMAGE2IMAGE_WORKFLOW : null);
}

// Entry point for the slash command: the reminder line, then the table.
export function openCharacterSheet(deps) {
  state.characterSheet = normalizeCharacterSheet(state.characterSheet);
  const wf = i2iWorkflow();
  addMessage('bot', `Character sheet — every panel is generated by your image2image workflow `
    + `<strong style="color:var(--neon)">${escapeHtml(wf || 'the first image2image workflow')}</strong> `
    + `(change it with <code>/i2i-workflow</code>). It needs <code>&lt;WIDTH&gt;</code>/<code>&lt;HEIGHT&gt;</code> `
    + `tokens for the panels to come out at their own shapes. Drop a detailed head-and-shoulders portrait into the top box.`);
  renderCharacterSheetTable(addMessage('bot', ''), deps);
  scrollBottom();
}

export function renderCharacterSheetTable(bubble, deps) {
  const root = document.createElement('div');
  root.className = 'charsheet';
  bubble.appendChild(root);

  // ---- input image -------------------------------------------------------
  const srcRow = document.createElement('div');
  srcRow.className = 'charsheet-source';
  const srcLabel = document.createElement('div');
  srcLabel.className = 'charsheet-label';
  srcLabel.textContent = 'Input image';
  const zone = document.createElement('div');
  zone.className = 'charsheet-drop';
  zone.title = 'Drag an image from the chat or your desktop here, or click to browse';
  const clearBtn = document.createElement('button');
  clearBtn.className = 'charsheet-icon-btn';
  clearBtn.textContent = '✕';
  clearBtn.title = 'Clear the input image';
  const fileInput = document.createElement('input');
  fileInput.type = 'file';
  fileInput.accept = 'image/*';
  fileInput.style.display = 'none';
  srcRow.append(srcLabel, zone, clearBtn, fileInput);
  root.appendChild(srcRow);

  // ---- panels ------------------------------------------------------------
  const rows = {};
  for (const panel of CHARACTER_SHEET_PANELS) {
    const row = document.createElement('div');
    row.className = 'charsheet-row';
    const left = document.createElement('div');
    left.className = 'charsheet-prompt';
    const label = document.createElement('div');
    label.className = 'charsheet-label';
    label.textContent = panel.label;
    const ta = document.createElement('textarea');
    ta.rows = 2;
    ta.value = sheet().prompts[panel.key] || '';
    ta.addEventListener('input', () => {
      sheet().prompts[panel.key] = ta.value;
      // Save only: a full redraw per keystroke would rebuild every thumbnail.
      document.dispatchEvent(new CustomEvent('character-sheet-edited'));
    });
    left.append(label, ta);

    const cell = document.createElement('div');
    cell.className = 'charsheet-cell';
    row.append(left, cell);
    root.appendChild(row);
    rows[panel.key] = { row, ta, cell };
  }

  // ---- footer ------------------------------------------------------------
  const footer = document.createElement('div');
  footer.className = 'charsheet-footer';
  const status = document.createElement('div');
  status.className = 'charsheet-status';
  const resetBtn = document.createElement('button');
  resetBtn.className = 'charsheet-link-btn';
  resetBtn.textContent = '⟲ Reset prompts';
  const cancelBtn = document.createElement('button');
  cancelBtn.className = 'charsheet-link-btn';
  cancelBtn.textContent = '✕ Cancel';
  const genBtn = document.createElement('button');
  genBtn.className = 'charsheet-generate';
  genBtn.textContent = 'Generate';
  footer.append(status, resetBtn, cancelBtn, genBtn);
  root.appendChild(footer);

  // ---- behaviour ---------------------------------------------------------
  function setSource(url) {
    const s = sheet();
    if (s.source === url) return;
    s.source = url;
    // The old panels show a different person — they no longer belong to this sheet.
    // The files are left in the gallery rather than deleted: they may still be wanted.
    s.results = {};
    lastError = null;
    notifyCharacterSheetChanged();
  }

  function flash(msg) {
    lastError = msg;
    redraw();
  }

  function acceptFile(file) {
    if (!file) return;
    if (!file.type.startsWith('image/')) { flash('That isn\'t an image'); return; }
    const fd = new FormData();
    fd.append('file', file);
    zone.textContent = 'Uploading…';
    fetch('/api/import-image', { method: 'POST', body: fd })
      .then(r => r.json())
      .then(data => {
        if (data.error) throw new Error(data.error);
        setSource(data.url);
      })
      .catch(err => flash(err.message || 'Upload failed'));
  }

  zone.addEventListener('click', () => { if (!busy()) fileInput.click(); });
  fileInput.addEventListener('change', e => { acceptFile(e.target.files[0]); e.target.value = ''; });
  zone.addEventListener('dragover', e => { e.preventDefault(); zone.classList.add('drag-over'); });
  zone.addEventListener('dragleave', () => zone.classList.remove('drag-over'));
  zone.addEventListener('drop', e => {
    e.preventDefault();
    // Let it bubble so the page-wide drop overlay closes, but stop that handler
    // importing the file into the chat as well.
    e.comfyDropHandled = true;
    zone.classList.remove('drag-over');
    if (busy()) { flash('Wait for the running job to finish'); return; }
    const files = Array.from(e.dataTransfer.files || []);
    if (files.length) { acceptFile(files[0]); return; }
    const url = e.dataTransfer.getData(COMFY_URL_DND_TYPE);
    if (!url) return;
    if (isVideoUrl(url) || !url.startsWith('/images/')) { flash('Drop a still image from the chat'); return; }
    setSource(url);
  });
  clearBtn.addEventListener('click', () => { if (!busy()) setSource(null); });

  resetBtn.addEventListener('click', () => {
    if (activeJob) return;
    sheet().prompts = defaultCharacterSheetPrompts();
    for (const { key } of CHARACTER_SHEET_PANELS) rows[key].ta.value = sheet().prompts[key];
    notifyCharacterSheetChanged();      // other open tables pick up the reset too
  });

  cancelBtn.addEventListener('click', () => {
    if (!activeJob || !activeJob.jobId) return;
    activeJob.status = 'Cancelling…';
    fetch('/api/cancel/' + activeJob.jobId, { method: 'POST' }).catch(() => {});
    redraw();
  });

  genBtn.addEventListener('click', () => {
    if (busy()) return;
    const s = sheet();
    const panels = characterSheetPanelsPayload(s);
    const missing = panels.find(p => !p.cached && !p.prompt);
    if (missing) {
      const label = CHARACTER_SHEET_PANELS.find(p => p.key === missing.key).label;
      flash(`${label} needs a prompt`);
      return;
    }
    startJob(panels, true, deps);
  });

  function drawCell(key) {
    const { row, cell, ta } = rows[key];
    const s = sheet();
    const url = s.results[key];
    const running = activeJob && activeJob.keys.has(key);
    const current = running && activeJob.current === key;
    cell.innerHTML = '';
    if (document.activeElement !== ta && ta.value !== (s.prompts[key] || '')) ta.value = s.prompts[key] || '';
    ta.disabled = !!activeJob;

    let fj = faceJobs[key];
    // The panel changed underneath a pending comparison (new chat, session load):
    // the detailed file belongs to nothing now.
    if (fj && fj.phase === 'compare' && s.results[key] !== fj.oldUrl) {
      deleteImageFile(fj.newUrl).catch(() => {});
      delete faceJobs[key];
      fj = null;
    }
    row.classList.toggle('comparing', !!(fj && fj.phase === 'compare'));
    if (fj && fj.phase === 'compare') {
      // Moving the one slider element here is fine: it's the same comparison wherever
      // it's shown, and its ✓/✗ settle it for every table.
      cell.appendChild(fj.slider);
      return;
    }

    if (url) {
      const thumb = document.createElement('div');
      thumb.className = 'charsheet-thumb';
      const img = document.createElement('img');
      img.src = url;
      img.draggable = true;
      img.addEventListener('dragstart', e => {
        e.dataTransfer.setData(COMFY_URL_DND_TYPE, url);
        e.dataTransfer.setData('text/uri-list', url);
      });
      img.addEventListener('click', () => {
        const all = CHARACTER_SHEET_PANELS.map(p => s.results[p.key]).filter(Boolean);
        openLightbox(url, all);
      });
      // A panel whose file has gone (deleted, archived) is just forgotten, so the
      // next Generate re-runs it.
      img.addEventListener('error', () => {
        if (sheet().results[key] === url) {
          delete sheet().results[key];
          notifyCharacterSheetChanged();
        }
      });
      thumb.appendChild(img);
      if (!running && !fj) {
        const regen = document.createElement('button');
        regen.className = 'charsheet-regen';
        regen.textContent = '↺';
        regen.title = 'Regenerate this panel (new seed, current prompt)';
        regen.disabled = busy();
        regen.addEventListener('click', e => { e.stopPropagation(); regenerate(key); });
        const face = document.createElement('button');
        face.className = 'charsheet-regen charsheet-face';
        face.innerHTML = '&#128100;&#xFE0E;';
        face.title = 'Run face detail on this panel';
        face.disabled = busy();
        face.addEventListener('click', e => { e.stopPropagation(); faceDetail(key); });
        thumb.append(face, regen);
      }
      if (running || (fj && fj.phase === 'running')) thumb.classList.add('stale');
      cell.appendChild(thumb);
      if (fj && fj.phase === 'running') {
        const cap = document.createElement('div');
        cap.className = 'progress-caption';
        cap.textContent = 'Face detailing… (progress below the table)';
        cell.appendChild(cap);
      }
    } else if (!running) {
      const empty = document.createElement('div');
      empty.className = 'charsheet-empty';
      empty.textContent = '—';
      cell.appendChild(empty);
    }

    if (running) {
      const prog = document.createElement('div');
      prog.className = 'charsheet-progress';
      const wrap = document.createElement('div');
      wrap.className = 'progress-bar-wrap';
      const bar = document.createElement('div');
      bar.className = 'progress-bar';
      wrap.appendChild(bar);
      const cap = document.createElement('div');
      cap.className = 'progress-caption';
      if (current) {
        const pct = activeJob.tick ? progressPercent(activeJob.tick) : null;
        if (pct !== null) { wrap.classList.add('determinate'); bar.style.width = pct + '%'; }
        cap.textContent = (activeJob.tick && progressCaption(activeJob.tick)) || 'Generating…';
      } else {
        cap.textContent = 'Queued';
        wrap.classList.add('determinate');
        bar.style.width = '0%';
      }
      prog.append(wrap, cap);
      cell.appendChild(prog);
    }
  }

  // 👤: the chat's face-detail dialog and job, then a before/after slider in this
  // panel's cell. 2 keeps the detailed panel (the old file is deleted, as a chat
  // image's slider does), 1 keeps the original, 🩹 composites the two.
  function faceDetail(key) {
    if (busy() || !deps.charsheetFaceDetail) return;
    const s = sheet();
    const oldUrl = s.results[key];
    if (!oldUrl) return;
    faceJobs[key] = { phase: 'dialog', oldUrl };     // locks the sheet while the dialog is up
    jobChanged();
    deps.charsheetFaceDetail(oldUrl, {
      dialogHost: rows[key].row, anchor: root, promptFrom: s.source,
      onStart: () => { faceJobs[key] = { phase: 'running', oldUrl }; jobChanged(); },
    })
      .then(res => {
        if (res) { showFaceCompare(key, res.oldUrl, res.newUrl); return; }
        if (faceJobs[key]) { delete faceJobs[key]; jobChanged(); }
      })
      .catch(() => { if (faceJobs[key]) { delete faceJobs[key]; jobChanged(); } });
  }

  function regenerate(key) {
    const s = sheet();
    const prompt = (s.prompts[key] || '').trim();
    if (!prompt) { flash('Enter a prompt first'); return; }
    startJob([{ key, prompt }], false, deps);
  }

  function redraw() {
    const s = sheet();
    zone.innerHTML = '';
    if (s.source) {
      const img = document.createElement('img');
      img.src = s.source;
      zone.appendChild(img);
    } else {
      zone.innerHTML = '<span class="charsheet-hint">Drop a head-and-shoulders portrait here — from the chat or your desktop</span>';
    }
    clearBtn.disabled = !s.source || busy();
    for (const { key } of CHARACTER_SHEET_PANELS) drawCell(key);

    genBtn.disabled = !s.source || busy();
    resetBtn.disabled = !!activeJob;
    cancelBtn.style.display = activeJob && activeJob.jobId ? '' : 'none';
    const have = CHARACTER_SHEET_PANELS.filter(p => s.results[p.key]).length;
    genBtn.textContent = have === CHARACTER_SHEET_PANELS.length ? 'Generate sheet (re-composite)'
      : have ? `Generate (${CHARACTER_SHEET_PANELS.length - have} to go)` : 'Generate';
    if (activeJob) {
      status.className = 'charsheet-status';
      status.textContent = activeJob.status || 'Working…';
    } else if (lastError) {
      status.className = 'charsheet-status error';
      status.textContent = '⚠ ' + lastError;
    } else {
      status.className = 'charsheet-status';
      status.textContent = s.source ? '' : 'No input image yet';
    }
  }

  // Redraw on every change; drop the listener once the bubble has left the page
  // (new chat, session load) so stale tables don't accumulate handlers.
  const onChange = () => {
    if (!root.isConnected) {
      document.removeEventListener('character-sheet-changed', onChange);
      document.removeEventListener('character-sheet-job', onChange);
      return;
    }
    redraw();
  };
  document.addEventListener('character-sheet-changed', onChange);
  document.addEventListener('character-sheet-job', onChange);
  redraw();
}

// A finished 👤 run: swap the panel's thumbnail for the usual before/after slider.
// Settling it writes the kept file back into the sheet (which saves the session).
function showFaceCompare(key, oldUrl, newUrl) {
  if (sheet().results[key] !== oldUrl) {
    deleteImageFile(newUrl).catch(() => {});
    delete faceJobs[key];
    jobChanged();
    return;
  }
  const settle = (keep, discard) => {
    delete faceJobs[key];
    const cur = sheet();
    if (cur.results[key] === oldUrl) {
      cur.results[key] = keep;
      discard.forEach(u => deleteImageFile(u).catch(() => {}));
    } else if (keep !== oldUrl) {
      deleteImageFile(keep).catch(() => {});      // the panel moved on; don't orphan it
    }
    notifyCharacterSheetChanged();
  };
  const slider = buildComparisonSlider(oldUrl, newUrl,
    () => settle(newUrl, [oldUrl]),
    () => settle(oldUrl, [newUrl]),
    compositeUrl => settle(compositeUrl, [oldUrl, newUrl]),
    null);
  slider.classList.add('charsheet-compare');
  faceJobs[key] = { phase: 'compare', oldUrl, newUrl, slider };
  jobChanged();
}

function jobChanged() {
  document.dispatchEvent(new CustomEvent('character-sheet-job'));
}

function startJob(panels, compose, deps) {
  if (busy()) return;
  const s = sheet();
  if (!s.source) return;
  const toRun = panels.filter(p => !p.cached).map(p => p.key);
  activeJob = { jobId: null, keys: new Set(toRun), current: null, status: 'Connecting…', tick: null };
  lastError = null;
  jobChanged();

  fetch('/api/character-sheet', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      image: s.source,
      workflow: i2iWorkflow() || undefined,
      panels,
      compose,
      ...(state.currentServer ? { server: state.currentServer.address, server_os: state.currentServer.os } : {}),
    }),
  })
    .then(r => r.json())
    .then(data => {
      if (data.error) throw new Error(data.error);
      activeJob.jobId = data.job_id;
      jobChanged();
      const es = new EventSource(`/api/progress/${data.job_id}`);
      es.onmessage = e => {
        const msg = JSON.parse(e.data);
        if (msg.type === 'progress') {
          activeJob.status = msg.message;
          jobChanged();
        } else if (msg.type === 'tick') {
          activeJob.tick = msg;
          jobChanged();
        } else if (msg.type === 'panel_start') {
          activeJob.current = msg.key;
          activeJob.tick = null;
          jobChanged();
        } else if (msg.type === 'panel') {
          const cur = sheet();
          const old = cur.results[msg.key];
          cur.results[msg.key] = msg.url;
          // Superseded by the regenerated panel, as a do-over replaces its image.
          if (old && old !== msg.url) deleteImageFile(old).catch(() => {});
          activeJob.keys.delete(msg.key);
          notifyCharacterSheetChanged();
        } else if (msg.type === 'done') {
          es.close();
          const url = (msg.images || [])[0];
          activeJob = null;
          if (url) addSheetToChat(url, deps);
          jobChanged();
        } else if (msg.type === 'error' || msg.type === 'cancelled') {
          es.close();
          activeJob = null;
          lastError = msg.type === 'cancelled' ? 'Cancelled' : (msg.message || 'Failed');
          jobChanged();
        }
      };
      es.onerror = () => {
        // The server closes the stream after a terminal event; only a drop before
        // that is a real failure.
        if (activeJob && activeJob.jobId === data.job_id) {
          es.close();
          activeJob = null;
          lastError = 'Lost connection to the job — check /jobs';
          jobChanged();
        }
      };
    })
    .catch(err => {
      activeJob = null;
      lastError = err.message || 'Request failed';
      jobChanged();
    });
}

function addSheetToChat(url, deps) {
  const bubble = addMessage('bot', '<div class="status-text">Character sheet — 3840×2160</div>');
  state.sessionImages.push(url);
  state.imagePrompts[url] = 'Character sheet';
  deps.appendChatImage(bubble, url);
  scrollBottom();
  notifyCharacterSheetChanged();      // also triggers the session save
}
